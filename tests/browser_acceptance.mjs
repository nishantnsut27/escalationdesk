async function capture(name, surface = page, audit = true) {
  await surface.evaluate(() => document.fonts.ready)
  await surface.waitForFunction(() => [...document.querySelectorAll('.chart-container')].every(chart => {
    const svg = chart.querySelector('svg.recharts-surface')
    return !svg || Math.abs(svg.getBoundingClientRect().width - chart.getBoundingClientRect().width) <= 1
  }))
  await surface.screenshot({ path: `${dir}/${name}.png`, fullPage: true })
  if (audit) {
    const report = await new AxeBuilder({ page: surface }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
    for (const item of report.violations) violations.push({ screen: name, id: item.id, impact: item.impact, description: item.description, nodes: item.nodes.map(node => ({ target: node.target, summary: node.failureSummary })) })
  }
}
